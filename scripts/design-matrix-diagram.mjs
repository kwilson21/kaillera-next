import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { currentDesignMatrix } from './check-design-matrix.ts';

const { requirements, parameters, current } = currentDesignMatrix();
const output = new URL('../docs/architecture/design-matrix.svg', import.meta.url);
const label = (id) =>
  id
    .replace(/^(FR|DP)-/, '')
    .split('-')
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(' ');
const xml = (value) =>
  String(value).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;');

const cell = 35;
const left = 154;
const top = 198;
const gridWidth = parameters.length * cell;
const gridHeight = requirements.length * cell;
const width = left + gridWidth + 38;
const height = top + gridHeight + 62;
const legendY = height - 28;
const rect = (x, y, w, h, fill, radius = 0) =>
  `<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="${radius}" fill="${fill}"/>`;
const text = (x, y, value, attributes = '') => `<text x="${x}" y="${y}" ${attributes}>${xml(value)}</text>`;

const lines = [
  '<!-- Generated by npm run diagram:matrix. -->',
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" width="${width}" height="${height}" role="img" aria-labelledby="title description">`,
  '<title id="title">Kaillera-next functional design matrix</title>',
  `<desc id="description">${xml(`${requirements.length} requirements and ${parameters.length} design parameters. ${current.offDiagonal} cross-dependencies. Rows are requirements. Columns are design parameters. A square marks the designated pair and a dot marks another dependency.`)}</desc>`,
  rect(0, 0, width, height, '#f6f8fc', 16),
  `<g fill="#162743" font-family="system-ui, sans-serif" font-size="13">`,
  text(24, 37, 'Kaillera-next functional design matrix', 'font-size="23" font-weight="700"'),
  text(
    24,
    63,
    `${requirements.length} requirements · ${current.offDiagonal} cross-dependencies · ${label(current.classification)}`,
    'fill="#465b78"',
  ),
  text(left, 99, 'Design parameters', 'font-weight="700"'),
  text(left - 12, top - 12, 'Requirements', 'text-anchor="end" font-weight="700"'),
];

for (const [column, parameter] of parameters.entries()) {
  const x = left + column * cell + cell / 2;
  const y = top - 10;
  lines.push(text(x, y, label(parameter), `transform="rotate(-57 ${x} ${y})"`));
}
for (const [row, requirement] of requirements.entries()) {
  const y = top + row * cell;
  lines.push(text(left - 12, y + cell / 2 + 5, label(requirement.id), 'text-anchor="end"'));
  for (const [column, parameter] of parameters.entries()) {
    const x = left + column * cell;
    lines.push(rect(x + 1, y + 1, cell - 2, cell - 2, row % 2 ? '#e6ecf5' : '#edf2f8', 4));
    if (!current.matrix[row][column]) continue;
    if (requirement.counterpart === parameter) {
      lines.push(rect(x + 8, y + 8, cell - 16, cell - 16, '#263f72', 4));
    } else {
      lines.push(`<circle cx="${x + cell / 2}" cy="${y + cell / 2}" r="8" fill="#007f79"/>`);
    }
  }
}
lines.push(
  rect(left, legendY - 10, 16, 16, '#263f72', 3),
  text(left + 24, legendY + 3, 'Designated pair'),
  `<circle cx="${left + 174}" cy="${legendY - 2}" r="7" fill="#007f79"/>`,
  text(left + 190, legendY + 3, 'Cross-dependency'),
  '</g>',
  '</svg>',
  '',
);
const svg = lines.join('\n');

if (process.argv.includes('--check')) {
  if (!existsSync(output) || readFileSync(output, 'utf8') !== svg) {
    console.error('Design matrix image is out of date. Run npm run diagram:matrix.');
    process.exitCode = 1;
  }
} else {
  writeFileSync(output, svg);
}
