"""Generate the client's Effect Schemas from the server's Pydantic models.

server/src/api/payloads.py is the one description of every Socket.IO
payload. This writes web/src/protocol.gen.ts from it: one Effect Schema, one
type and one decode helper per model, so the client cannot drift from what
the server validates and sends.

    npm run protocol         # regenerate
    npm run protocol:check   # fail if the committed file is stale (CI)

A type this script cannot translate stops it with an error, so a new kind of
field has to be taught here before it can ship half-described.
"""

from __future__ import annotations

import difflib
import json
import sys
import types
from pathlib import Path
from typing import Any, Literal, Union, get_args, get_origin

import annotated_types as at
from pydantic import BaseModel
from pydantic.fields import FieldInfo

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "web" / "src" / "protocol.gen.ts"
SOURCE = "server/src/api/payloads.py"

HEADER = f"""\
/**
 * Generated by scripts/gen_protocol.py from {SOURCE}.
 * Do not edit: change the Pydantic model and run `npm run protocol`.
 *
 * Client-to-server payloads mark every field the server defaults as optional.
 * Server-to-client payloads list every key the server sends; unknown keys are
 * ignored on decode, so a newer server does not break an older page.
 */
import {{ Schema }} from 'effect';
"""


class Unsupported(TypeError):
    pass


def _ts_string(value: str) -> str:
    """A single-quoted TypeScript string literal, as oxfmt would print it."""
    return "'" + json.dumps(value)[1:-1].replace('\\"', '"').replace("'", "\\'") + "'"


def _ts_literal(value: Any) -> str:
    if isinstance(value, str):
        return _ts_string(value)
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    raise Unsupported(f"literal value {value!r}")


def _ts_key(name: str) -> str:
    return name if name.isidentifier() else _ts_string(name)


def _checks(base: type, metadata: list[Any], where: str) -> str:
    """The `.check(...)` suffix for a field's constraints, or ''."""
    low = high = min_len = max_len = None
    for m in metadata:
        if isinstance(m, at.Ge):
            low = m.ge
        elif isinstance(m, at.Le):
            high = m.le
        elif isinstance(m, at.MinLen):
            min_len = m.min_length
        elif isinstance(m, at.MaxLen):
            max_len = m.max_length
        else:
            raise Unsupported(f"{where}: constraint {m!r}")
    checks: list[str] = []
    if base is str:
        # Pydantic counts code points, not UTF-16 units.
        if min_len is not None:
            checks.append(f"Schema.isMinCodePoints({min_len})")
        if max_len is not None:
            checks.append(f"Schema.isMaxCodePoints({max_len})")
        if low is not None or high is not None:
            raise Unsupported(f"{where}: numeric bound on a string")
    elif base in (int, float):
        if low is not None and high is not None:
            checks.append(f"Schema.isBetween({{ minimum: {low}, maximum: {high} }})")
        elif low is not None:
            checks.append(f"Schema.isGreaterThanOrEqualTo({low})")
        elif high is not None:
            checks.append(f"Schema.isLessThanOrEqualTo({high})")
        if min_len is not None or max_len is not None:
            raise Unsupported(f"{where}: length bound on a number")
    elif metadata:
        raise Unsupported(f"{where}: constraints on {base!r}")
    return f".check({', '.join(checks)})" if checks else ""


class Generator:
    def __init__(self, module: types.ModuleType):
        self.module = module
        # Named Literal aliases (RoomStatus = Literal[...]) become named schemas.
        self.literals: dict[str, Any] = {
            name: value
            for name, value in vars(module).items()
            if not name.startswith("_") and get_origin(value) is Literal
        }
        self.models: list[type[BaseModel]] = [
            value
            for name, value in vars(module).items()
            if isinstance(value, type)
            and issubclass(value, BaseModel)
            and value.__module__ == module.__name__
            and not name.startswith("_")
        ]
        self.emitted: set[str] = set()

    def _type(self, tp: Any, metadata: list[Any], where: str) -> str:
        origin = get_origin(tp)
        if origin in (Union, types.UnionType):
            args = get_args(tp)
            rest = [a for a in args if a is not type(None)]
            if len(rest) != 1 or len(rest) == len(args):
                raise Unsupported(f"{where}: union {tp!r} (only `X | None` is supported)")
            return f"Schema.NullOr({self._type(rest[0], metadata, where)})"
        if origin is Literal:
            if metadata:
                raise Unsupported(f"{where}: constraints on a Literal")
            for name, alias in self.literals.items():
                if alias == tp:
                    return name
            return self._literal(tp)
        if tp is str:
            return "Schema.String" + _checks(str, metadata, where)
        if tp is bool:
            return "Schema.Boolean" + _checks(bool, metadata, where)
        if tp is int:
            return "Schema.Int" + _checks(int, metadata, where)
        if tp is float:
            return "Schema.Number" + _checks(float, metadata, where)
        if metadata:
            raise Unsupported(f"{where}: constraints on {tp!r}")
        if tp is Any:
            return "Schema.Unknown"
        if tp is list or origin is list:
            (item,) = get_args(tp) or (Any,)
            return f"Schema.Array({self._type(item, [], where)})"
        if tp is dict or origin is dict:
            key, value = get_args(tp) or (str, Any)
            if key is not str:
                raise Unsupported(f"{where}: dict key {key!r} (JSON object keys are strings)")
            return f"Schema.Record(Schema.String, {self._type(value, [], where)})"
        if isinstance(tp, type) and issubclass(tp, BaseModel):
            if tp.__name__ not in self.emitted:
                raise Unsupported(f"{where}: {tp.__name__} is not a model defined earlier in {SOURCE}")
            return tp.__name__
        raise Unsupported(f"{where}: type {tp!r}")

    @staticmethod
    def _literal(tp: Any) -> str:
        values = [_ts_literal(v) for v in get_args(tp)]
        if len(values) == 1:
            return f"Schema.Literal({values[0]})"
        return f"Schema.Literals([{', '.join(values)}])"

    def _field(self, model: type[BaseModel], name: str, field: FieldInfo) -> str:
        where = f"{model.__name__}.{name}"
        schema = self._type(field.annotation, list(field.metadata), where)
        if not field.is_required():
            schema = f"Schema.optional({schema})"
        return f"  {_ts_key(field.alias or name)}: {schema},"

    def _model(self, model: type[BaseModel]) -> str:
        name = model.__name__
        lines: list[str] = []
        doc = (model.__doc__ or "").strip() if "__doc__" in vars(model) else ""
        if doc:
            body = doc.splitlines()
            if len(body) == 1:
                lines.append(f"/** {body[0]} */")
            else:
                lines += ["/**", *[f" * {line.strip()}".rstrip() for line in body], " */"]
        fields = [self._field(model, n, f) for n, f in model.model_fields.items()]
        if fields:
            lines += [f"export const {name} = Schema.Struct({{", *fields, "});"]
        else:
            lines.append(f"export const {name} = Schema.Struct({{}});")
        lines.append(f"export type {name} = typeof {name}.Type;")
        self.emitted.add(name)
        return "\n".join(lines)

    def render(self) -> str:
        blocks = [HEADER.rstrip("\n")]
        for name, alias in self.literals.items():
            blocks.append(f"export const {name} = {self._literal(alias)};\nexport type {name} = typeof {name}.Type;")
            self.emitted.add(name)
        blocks += [self._model(m) for m in self.models]
        blocks.append(
            "\n".join(
                f"export const decode{m.__name__} = Schema.decodeUnknownResult({m.__name__});" for m in self.models
            )
        )
        return "\n\n".join(blocks) + "\n"


def generate() -> str:
    sys.path.insert(0, str(ROOT / "server"))
    from src.api import payloads

    return Generator(payloads).render()


def main(argv: list[str]) -> int:
    text = generate()
    if "--check" not in argv:
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)}")
        return 0
    current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    if current == text:
        return 0
    rel = str(OUT.relative_to(ROOT))
    sys.stdout.writelines(
        difflib.unified_diff(
            current.splitlines(True), text.splitlines(True), f"{rel} (committed)", f"{rel} (generated)"
        )
    )
    print(f"\n{rel} is stale: run `npm run protocol` and commit the result.", file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
