/** Generate the recovery lifecycle from actual XState transitions, not a hand-maintained graph. */
import fs from 'node:fs';
import { initialTransition, transition } from 'xstate';
import { checkpointMachine } from '../web/src/checkpoint-machine.ts';
import { recoveryMachine } from '../web/src/recovery-delivery.ts';
const out = new URL('../docs/recovery-machine.md', import.meta.url);
const [initial] = initialTransition(recoveryMachine, {
  sid: 'guest',
  slot: 1,
  hole: 900,
  firstFrame: 1000,
  now: 0,
  pushes: 1,
  maxPushes: 3,
  timeoutMs: 5000,
  quietMs: 20000,
});
const queue = [initial],
  seen = new Set(),
  edges = new Set();
while (queue.length) {
  const state = queue.shift();
  const key = `${state.value}:${state.context.attempt}`;
  if (seen.has(key) || state.status === 'done') continue;
  seen.add(key);
  const attempt = state.context.attempt;
  for (const [label, event] of [
    ['delivered', { type: 'delivered', attempt, now: 0, before: 997 }],
    ['failed', { type: 'failed', attempt, now: 0 }],
    ['acknowledged', { type: 'acknowledged', before: 997 }],
    ['deadline', { type: 'tick', now: 60000 * attempt, away: false, chainProgress: 0 }],
    ['peer gone', { type: 'tick', now: 0, away: true, chainProgress: 0 }],
    ['stop', { type: 'stop' }],
  ]) {
    const [next] = transition(recoveryMachine, state, event);
    if (next.value !== state.value || next.context.attempt !== attempt)
      edges.add(`  ${state.value} -->|${label}| ${next.value}`);
    queue.push(next);
  }
}
const [start] = initialTransition(checkpointMachine);
const pending = [start],
  visited = new Set(),
  checkpointEdges = [];
while (pending.length) {
  const state = pending.shift();
  if (visited.has(state.value)) continue;
  visited.add(state.value);
  for (const event of Object.keys(checkpointMachine.config.states[state.value].on ?? {})) {
    const [next] = transition(checkpointMachine, state, { type: event });
    checkpointEdges.push(`  ${state.value} -->|${event.toLowerCase()}| ${next.value}`);
    pending.push(next);
  }
}
const content = `# Per-recipient recovery\n\nGenerated by scripts/recovery-diagram.mjs from web/src/recovery-delivery.ts.\n\n\`\`\`mermaid\nflowchart TD\n${[...edges].sort().join('\n')}\n\`\`\`\n\nEach recipient owns its acknowledgement, delivery/backoff clock, and bounded attempt count.\nTicks use the game's freeze-credited clock; independent wall timers would charge host freezes to guests.
An in-flight recipient with chain progress remains sending. Quiet/no-progress work takes the bounded retry/drop path,
matching the pre-actor lifecycle. Logical exhaustion never frees an uncancellable physical operation early.\nThe machine emits commands through Effect, and Effect acquire/use/release owns capture and transfer reservations.\nA reservation survives actor reset until its physical operation settles; each recipient releases independently.\nCancellation skips queued work before it writes a header. Already-started transfers drain their framing,
keep their permit until settled, and cannot update a cancelled/replaced actor.
Immutable token identity prevents a stale completion from changing a new attempt or releasing its permit.\nResync disabled prevents recovery startup; toggling it off cancels existing actors, not the normal stall path.\n\nModel: specs/recovery_delivery.qnt (actor, delivery, capacity and reservation invariants).\n`;
const both =
  content + '\n## Verified checkpoint recovery\n\n```mermaid\nflowchart TD\n' + checkpointEdges.join('\n') + '\n```\n';
if (process.argv.includes('--check')) {
  if (fs.readFileSync(out, 'utf8') !== both) throw new Error('Recovery diagram is out of date');
} else fs.writeFileSync(out, both);
