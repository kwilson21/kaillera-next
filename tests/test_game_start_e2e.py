"""What each page in a room does when the host starts and ends a game.

onGameStarted and onGameEnded in play.js carry out what
web/src/play/game-start.ts (proved) decides. This walks every answer it can
give on real pages. Through the server: a player plays, a spectator
watches, a guest without the ROM keeps the host's offer up, a guest who
drops a ROM that is not the host's is refused and keeps the offer up at the
start, all return to the lobby at the end, and a late copy of that end does
not end the next match. The answers a real room does not reach on
demand are driven through the page's own socket handlers with a made-up
message (a harness step): a player who took the host's ROM before it
arrived, and the two ends a page ignores (one with no game on, and the same
match's end a second time). `wrongRom` is not reached: a ROM that is not
the host's is refused as it is dropped, and the start message's host ROM
unloads one before the plan is asked.

The ROM is generated bytes, not a game, and nothing is booted
(`__test_skipBoot`). The streamed game's guest is covered by
tests/ts/play-game-start.test.ts, which also holds the rules to the old
branches over every input.

Run: pytest tests/test_game_start_e2e.py -v   (needs the server running)
"""

from playwright.sync_api import expect

ROM = {"name": "test.z64", "mimeType": "application/octet-stream", "buffer": bytes(i % 251 for i in range(200_000))}
OTHER_ROM = {
    "name": "other.z64",
    "mimeType": "application/octet-stream",
    "buffer": bytes(i % 241 for i in range(200_000)),
}
ENDED = "The host has ended the game"

# Deliver a message to the page's own handler for a server event, as if the
# server had sent it (the harness step for answers a real room doesn't reach
# on demand).
_DELIVER = """([event, data]) => {
    const handlers = window.__test_socket.listeners(event);
    if (!handlers.length) throw new Error('no handler for ' + event);
    for (const handler of handlers) handler(data);
}"""


def _open(browser, url):
    page = browser.new_page()
    page.add_init_script("window.__test_skipBoot = true;")
    page.goto(url)
    expect(page.locator("#overlay")).to_be_visible(timeout=10000)
    page.wait_for_function("window.__test_socket && window.__test_socket.connected", timeout=10000)
    return page


def _load_rom(page, rom=ROM):
    page.set_input_files("#rom-drop input[type=file]", rom)
    expect(page.locator("#rom-status")).to_contain_text(rom["name"], timeout=15000)


def _share_rom(host, guest):
    sharing = host.locator("#opt-rom-sharing")
    expect(sharing).to_be_enabled(timeout=10000)
    host.evaluate("document.querySelector('#host-controls .advanced-options')?.setAttribute('open', '')")
    sharing.check()
    guest.wait_for_function("window.__test_socket.connected", timeout=10000)


def _in_match(page):
    page.wait_for_function("!!window.KNState.matchId", timeout=10000)


# Count "game ended" toasts added from now on (a toast removes itself after a
# few seconds, so the ones on screen are not a count).
_COUNT_ENDED_TOASTS = """(text) => {
    window.__endedToasts = 0;
    new MutationObserver((records) => {
        for (const record of records)
            for (const node of record.addedNodes)
                if (node.classList?.contains('toast') && node.textContent.includes(text)) window.__endedToasts++;
    }).observe(document.getElementById('toast-container'), { childList: true });
}"""


def _ended_toasts_after(page, event):
    page.evaluate(_COUNT_ENDED_TOASTS, ENDED)
    page.evaluate(_DELIVER, ["game-ended", event])
    page.wait_for_timeout(300)
    return page.evaluate("window.__endedToasts")


def test_players_play_and_a_spectator_watches_then_all_return_to_the_lobby(browser, server_url, room):
    pages = []
    try:
        host = _open(browser, f"{server_url}/play.html?room={room}&host=1&name=Host")
        pages.append(host)
        _load_rom(host)
        guest = _open(browser, f"{server_url}/play.html?room={room}&name=Guest")
        pages.append(guest)
        _load_rom(guest)
        watcher = _open(browser, f"{server_url}/play.html?room={room}&name=Watcher&spectate=1")
        pages.append(watcher)
        expect(host.locator("#spectator-list")).to_have_text("Watching: Watcher", timeout=10000)

        expect(host.locator("#start-btn")).to_be_enabled(timeout=10000)
        host.click("#start-btn")
        for page in pages:
            _in_match(page)
            expect(page.locator("#overlay")).to_be_hidden(timeout=10000)
        match_id = guest.evaluate("window.KNState.matchId")

        host.evaluate("window.__test_socket.emit('end-game', {})")
        for page in pages:
            page.wait_for_function("!window.KNState.matchId", timeout=10000)
            expect(page.locator("#overlay")).to_be_visible(timeout=10000)
            expect(page.locator("#toast-container .toast", has_text=ENDED)).to_have_count(1)

        # The same match's end again is not handled a second time, not even
        # once the next match is on: it must not end that one.
        assert _ended_toasts_after(guest, {"matchId": match_id}) == 0
        expect(host.locator("#start-btn")).to_be_enabled(timeout=10000)
        host.click("#start-btn")
        guest.wait_for_function(f"window.KNState.matchId && window.KNState.matchId !== {match_id!r}", timeout=10000)
        next_match = guest.evaluate("window.KNState.matchId")
        assert _ended_toasts_after(guest, {"matchId": match_id}) == 0
        expect(guest.locator("#overlay")).to_be_hidden()
        assert guest.evaluate("window.KNState.matchId") == next_match
    finally:
        for page in pages:
            page.close()


def test_a_guest_without_the_rom_keeps_the_hosts_offer_up_when_the_game_starts(browser, server_url, room):
    pages = []
    try:
        host = _open(browser, f"{server_url}/play.html?room={room}&host=1&name=Host")
        pages.append(host)
        _load_rom(host)
        guest = _open(browser, f"{server_url}/play.html?room={room}&name=Guest")
        pages.append(guest)
        expect(host.locator("#player-list")).to_contain_text("Guest", timeout=10000)

        _share_rom(host, guest)
        expect(guest.locator("#rom-sharing-prompt")).to_be_visible(timeout=10000)

        expect(host.locator("#start-btn")).to_be_enabled(timeout=10000)
        host.click("#start-btn")
        _in_match(guest)
        # Undecided: the lobby stays up with the offer, and nothing boots.
        expect(guest.locator("#overlay")).to_be_visible()
        expect(guest.locator("#rom-sharing-prompt")).to_be_visible()
    finally:
        for page in pages:
            page.close()


def _guest_in_a_room(browser, server_url, room):
    host = _open(browser, f"{server_url}/play.html?room={room}&host=1&name=Host")
    guest = _open(browser, f"{server_url}/play.html?room={room}&name=Guest")
    expect(host.locator("#player-list")).to_contain_text("Guest", timeout=10000)
    return host, guest


def test_a_rom_that_is_not_the_hosts_is_refused_and_the_start_keeps_the_offer_up(browser, server_url, room):
    # A ROM that is not the host's is refused as it is dropped (and would be
    # unloaded again by the start message's host ROM), so a page never takes
    # one into the start: it decides with no ROM and keeps the offer up.
    host, guest = _guest_in_a_room(browser, server_url, room)
    try:
        _load_rom(host)
        _share_rom(host, guest)
        guest.set_input_files("#rom-drop input[type=file]", OTHER_ROM)
        expect(guest.locator("#rom-mismatch")).to_contain_text("doesn't match", timeout=15000)
        expect(host.locator("#start-btn")).to_be_enabled(timeout=10000)
        host.click("#start-btn")
        _in_match(guest)
        expect(guest.locator("#rom-status")).not_to_contain_text("other.z64")
        expect(guest.locator("#overlay")).to_be_visible()
        expect(guest.locator("#rom-sharing-prompt")).to_be_visible()
        expect(guest.locator("#error-msg")).to_be_hidden()
    finally:
        host.close()
        guest.close()


def test_a_player_who_took_the_hosts_rom_waits_for_it_in_the_lobby(browser, server_url, room):
    host, guest = _guest_in_a_room(browser, server_url, room)
    try:
        guest.evaluate(_DELIVER, ["rom-sharing-updated", {"romSharing": True}])
        expect(guest.locator("#rom-sharing-prompt")).to_be_visible(timeout=5000)
        guest.click("#rom-accept-btn")
        expect(guest.locator("#rom-transfer-progress")).to_be_visible(timeout=5000)

        guest.evaluate(
            _DELIVER,
            ["game-started", {"mode": "rollback", "resyncEnabled": True, "gameId": "", "matchId": "m-await"}],
        )
        # Not booted: the lobby stays up with the transfer, no offer, no error.
        expect(guest.locator("#overlay")).to_be_visible()
        expect(guest.locator("#rom-transfer-progress")).to_be_visible()
        expect(guest.locator("#rom-sharing-prompt")).to_be_hidden()
        expect(guest.locator("#error-msg")).to_be_hidden()
    finally:
        host.close()
        guest.close()


def test_a_page_with_no_game_on_ignores_a_game_end(browser, server_url, room):
    host, guest = _guest_in_a_room(browser, server_url, room)
    try:
        assert _ended_toasts_after(guest, {"matchId": "m-not-mine"}) == 0
        expect(guest.locator("#overlay")).to_be_visible()
    finally:
        host.close()
        guest.close()
