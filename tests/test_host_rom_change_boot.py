"""The host changes ROM in the lobby, and the game then boots and runs on both pages.

tests/test_game_start_e2e.py walks the host's ROM change on generated bytes
and boots nothing. These take the same orderings to a real start with the real
game (KN_ROM; skipped without it): the host's first ROM is generated bytes,
and it changes to the game.

- The guest drops the game while the host's copy is still being hashed
  (specs/rom_identity.qnt, hostChangesToTheGuestsRomTest). It is not refused,
  the host's start is taken, and both pages boot it and play.
- The guest dropped the game before the host changed to it, and it was refused
  then (guestDroppedFirstTest). The guest's page takes it from its ROM library
  when the room names it; that copy boots and plays.

Run: KN_ROM=/path/ssb64-us.z64 pytest tests/test_host_rom_change_boot.py -v   (needs the server running)
"""

import os

from playwright.sync_api import expect
from test_game_start_e2e import (
    _HOLD_READS,
    _RECORD_ROM_READY,
    _RECORD_ROOM,
    _RELEASE_READS,
    _WATCH_REFUSAL,
    OTHER_ROM,
    _heard_everything_from,
)

# A start ends a page's game with one of these in its sync log.
_FAILED = ("START-FAIL", "FATAL-")


def _open(browser, url):
    page = browser.new_page()
    page.goto(url)
    expect(page.locator("#overlay")).to_be_visible(timeout=10000)
    page.wait_for_function(
        "window.__test_socket && window.__test_socket.connected", timeout=10000
    )
    return page


def _host_on_other_rom_and_a_guest(browser, server_url, room):
    host = _open(
        browser, f"{server_url}/play.html?room={room}&host=1&name=Host&mode=rollback"
    )
    guest = _open(browser, f"{server_url}/play.html?room={room}&name=Guest")
    expect(host.locator("#player-list")).to_contain_text("Guest", timeout=10000)
    host.set_input_files("#rom-drop input[type=file]", OTHER_ROM)
    host.wait_for_function("() => !!window.KNState?.romHash", timeout=15000)
    expect(guest.locator("#host-rom-info")).to_contain_text("Host ROM:", timeout=10000)
    return host, guest


def _frame(page):
    return page.evaluate(
        "window.NetplayRollback?.getHudCounters?.()?.currentFrame ?? 0"
    )


def _both_play_the_hosts_rom(host, guest, start_game):
    """Start, and check both pages run the host's ROM and their frames go on."""
    host_hash = host.evaluate("window.KNState.romHash")
    assert guest.evaluate("window.KNState.romHash") == host_hash
    start_game(host, guest, timeout_s=300)
    for page in (host, guest):
        page.wait_for_function(
            "(window.NetplayRollback?.getHudCounters?.()?.currentFrame ?? 0) > 120",
            timeout=180000,
        )
    host_then, guest_then = _frame(host), _frame(guest)
    host.wait_for_timeout(3000)
    assert _frame(host) > host_then
    assert _frame(guest) > guest_then
    for page in (host, guest):
        assert page.evaluate("window.KNState.romHash") == host_hash
        log = page.evaluate("window.NetplayRollback.exportSyncLog()")
        assert not any(tag in log for tag in _FAILED), log[-3000:]


def test_a_guest_holding_the_game_the_host_changes_to_plays_it(
    browser, server_url, rom_path, room, start_game
):
    host, guest = _host_on_other_rom_and_a_guest(browser, server_url, room)
    try:
        old_hash = host.evaluate("window.KNState.romHash")
        guest.evaluate(_RECORD_ROOM)
        guest.evaluate(_RECORD_ROM_READY)
        guest.evaluate(_WATCH_REFUSAL)
        host.evaluate(_HOLD_READS)
        host.set_input_files("#rom-drop input[type=file]", rom_path)
        # The guest has heard the host's drop, then drops the game, whose hash
        # lands while the host's is held.
        _heard_everything_from(host, guest, "Host 2")
        guest.set_input_files("#rom-drop input[type=file]", rom_path)
        guest.wait_for_function(
            "(old) => window.__refusedShown || (!!window.KNState.romHash && window.KNState.romHash !== old)",
            arg=old_hash,
            timeout=30000,
        )
        assert not guest.evaluate("window.__refusedShown"), (
            "the host's new ROM was refused against its previous one"
        )
        expect(guest.locator("#host-rom-info")).to_contain_text("Host is loading a ROM")
        assert not any(m.get("ready") for m in guest.evaluate("window.__romReady"))
        new_hash = guest.evaluate("window.KNState.romHash")
        host.evaluate(_RELEASE_READS)
        host.wait_for_function(
            "(h) => window.KNState.romHash === h", arg=new_hash, timeout=30000
        )
        guest.wait_for_function(
            "(h) => window.__romReady.some((m) => m.ready && m.hash === h)",
            arg=new_hash,
            timeout=10000,
        )
        _both_play_the_hosts_rom(host, guest, start_game)
        assert not guest.evaluate("window.__refusedShown")
    finally:
        host.close()
        guest.close()


def test_a_game_the_guest_dropped_before_the_host_changed_to_it_boots_from_the_library(
    browser, server_url, rom_path, room, start_game
):
    host, guest = _host_on_other_rom_and_a_guest(browser, server_url, room)
    try:
        # Dropped before the host changes: refused, and kept in the library.
        guest.set_input_files("#rom-drop input[type=file]", rom_path)
        expect(guest.locator("#rom-mismatch")).to_contain_text(
            "doesn't match", timeout=30000
        )
        library_rom = guest.locator("#rom-library .rom-library-item")
        expect(library_rom).to_have_count(1, timeout=30000)
        game_hash = library_rom.get_attribute("data-hash")
        guest.evaluate(_RECORD_ROM_READY)
        host.set_input_files("#rom-drop input[type=file]", rom_path)
        host.wait_for_function(
            "(h) => window.KNState.romHash === h", arg=game_hash, timeout=30000
        )
        # The room names the game: the guest's page loads it from the library.
        guest.wait_for_function(
            "(h) => window.__romReady.some((m) => m.ready && m.hash === h)",
            arg=game_hash,
            timeout=30000,
        )
        expect(guest.locator("#rom-status")).to_contain_text(os.path.basename(rom_path))
        _both_play_the_hosts_rom(host, guest, start_game)
    finally:
        host.close()
        guest.close()
