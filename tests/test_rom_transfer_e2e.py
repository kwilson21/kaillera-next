"""A real ROM transfer between two browsers, in the lobby.

The host loads a file, shares it, the guest accepts, and the bytes cross a
WebRTC DataChannel. play.js's receiver is in charge; web/src/play/rom-transfer.ts
is given every event beside it and a difference is reported as a
`play-disagree` client event. This checks that the file arrives whole and
that, through the whole transfer, the two agree.

The file is 300 KB of generated bytes, not a game: nothing is booted.

Not covered: a transfer that is interrupted and resumed, and the mid-game
path over the engine's connection (both need a running match).

Run: pytest tests/test_rom_transfer_e2e.py -v   (needs the server running)
"""

import json

from playwright.sync_api import expect

ROM_BYTES = 300_000

# Client events leave through navigator.sendBeacon with a Blob body, which the
# browser does not expose to request listeners: keep a readable copy.
_KEEP_BEACONS = """
    window.__beacons = [];
    const send = navigator.sendBeacon.bind(navigator);
    navigator.sendBeacon = (url, body) => {
        if (String(url).includes('/api/client-event') && body && body.text) {
            body.text().then((text) => window.__beacons.push(text));
        }
        return send(url, body);
    };
"""


def _open(browser, url):
    page = browser.new_page()
    page.add_init_script(_KEEP_BEACONS)
    page.add_init_script("window.__test_skipBoot = true;")
    page.goto(url)
    expect(page.locator("#overlay")).to_be_visible(timeout=10000)
    page.wait_for_function("window.__test_socket && window.__test_socket.connected", timeout=10000)
    return page


def _disagreements(page):
    # Any comparison sends what is waiting; this one is certain to be made with a token.
    page.wait_for_function("!!window.KNState.uploadToken", timeout=10000)
    page.evaluate("window.getDelayPreference()")
    page.wait_for_timeout(300)
    events = [json.loads(text) for text in page.evaluate("window.__beacons")]
    return [e for e in events if e.get("type") == "play-disagree"]


def test_guest_receives_the_hosts_rom_and_the_rules_agree(browser, server_url, room):
    rom = bytes((i * 31 + 7) % 251 for i in range(ROM_BYTES))
    host = _open(browser, f"{server_url}/play.html?room={room}&host=1&name=Host")
    guest = None
    try:
        host.set_input_files(
            "#rom-drop input[type=file]", {"name": "test.z64", "mimeType": "application/octet-stream", "buffer": rom}
        )
        expect(host.locator("#rom-status")).to_contain_text("test.z64", timeout=15000)

        guest = _open(browser, f"{server_url}/play.html?room={room}&name=Guest")
        expect(host.locator("#player-list")).to_contain_text("Guest", timeout=10000)

        sharing = host.locator("#opt-rom-sharing")
        expect(sharing).to_be_enabled(timeout=10000)
        host.evaluate("document.querySelector('#host-controls .advanced-options')?.setAttribute('open', '')")
        sharing.check()

        expect(guest.locator("#rom-sharing-prompt")).to_be_visible(timeout=10000)
        guest.click("#rom-accept-btn")

        expect(guest.locator("#rom-status")).to_contain_text("test.z64 (from host)", timeout=30000)
        expect(guest.locator("#rom-transfer-progress")).to_be_hidden()

        assert _disagreements(guest) == []
        assert _disagreements(host) == []
    finally:
        host.close()
        if guest:
            guest.close()
