"""A real ROM transfer between two browsers, in the lobby.

The host loads a file, shares it, the guest accepts, and the bytes cross a
WebRTC DataChannel. Where the guest's transfer stands, and what it does next,
is web/src/play/rom-transfer.ts's receiverStep, which play.js's receiver
moves on every event. This checks that the file arrives whole, and, with a
chunk the host's page drops on purpose, that a short file is refused and the
next transfer starts it again from nothing (specs/rom_transfer.qnt,
`countIsHeld`).

The file is 300 KB of generated bytes, not a game: nothing is booted.

Not covered: a channel that closes mid-transfer and is resumed, and the
mid-game path over the engine's connection.

Run: pytest tests/test_rom_transfer_e2e.py -v   (needs the server running)
"""

from playwright.sync_api import expect

ROM_BYTES = 300_000

# The host's page drops its Nth binary send on a rom-transfer channel, once
# (`window.__dropRomChunk`, 0 = none): the guest is then told the file is
# complete with a chunk missing.
_DROP_A_CHUNK = """
    window.__dropRomChunk = 0;
    let sent = 0;
    const send = RTCDataChannel.prototype.send;
    RTCDataChannel.prototype.send = function (data) {
        if (this.label === 'rom-transfer' && data instanceof ArrayBuffer && window.__dropRomChunk > 0) {
            sent += 1;
            if (sent === window.__dropRomChunk) {
                window.__dropRomChunk = 0;
                return undefined;
            }
        }
        return send.call(this, data);
    };
"""


def _open(browser, url, *scripts):
    page = browser.new_page()
    for script in scripts:
        page.add_init_script(script)
    page.add_init_script("window.__test_skipBoot = true;")
    page.goto(url)
    expect(page.locator("#overlay")).to_be_visible(timeout=10000)
    page.wait_for_function("window.__test_socket && window.__test_socket.connected", timeout=10000)
    return page


ROM = bytes((i * 31 + 7) % 251 for i in range(ROM_BYTES))

# What the guest holds once a file has arrived: its size, and a sum of its bytes.
_RECEIVED = """async () => {
    const blob = window.__test_romBlob?.();
    if (!blob) return null;
    const bytes = new Uint8Array(await blob.arrayBuffer());
    let sum = 0;
    for (const b of bytes) sum = (sum * 31 + b) % 1000000007;
    return { size: bytes.length, sum };
}"""


def _sum(data):
    total = 0
    for b in data:
        total = (total * 31 + b) % 1000000007
    return total


def _share(browser, server_url, room, *host_scripts):
    """A host with the file loaded and sharing it, and a guest offered it."""
    host = _open(browser, f"{server_url}/play.html?room={room}&host=1&name=Host", *host_scripts)
    host.set_input_files(
        "#rom-drop input[type=file]", {"name": "test.z64", "mimeType": "application/octet-stream", "buffer": ROM}
    )
    expect(host.locator("#rom-status")).to_contain_text("test.z64", timeout=15000)

    guest = _open(browser, f"{server_url}/play.html?room={room}&name=Guest")
    expect(host.locator("#player-list")).to_contain_text("Guest", timeout=10000)

    sharing = host.locator("#opt-rom-sharing")
    expect(sharing).to_be_enabled(timeout=10000)
    host.evaluate("document.querySelector('#host-controls .advanced-options')?.setAttribute('open', '')")
    sharing.check()
    expect(guest.locator("#rom-sharing-prompt")).to_be_visible(timeout=10000)
    return host, guest


def test_guest_receives_the_hosts_rom(browser, server_url, room):
    host = guest = None
    try:
        host, guest = _share(browser, server_url, room)
        guest.click("#rom-accept-btn")

        expect(guest.locator("#rom-status")).to_contain_text("test.z64 (from host)", timeout=30000)
        expect(guest.locator("#rom-transfer-progress")).to_be_hidden()
        assert guest.evaluate(_RECEIVED) == {"size": ROM_BYTES, "sum": _sum(ROM)}
    finally:
        for page in (host, guest):
            if page:
                page.close()


def test_a_short_file_is_refused_and_the_next_transfer_starts_from_nothing(browser, server_url, room):
    host = guest = None
    try:
        host, guest = _share(browser, server_url, room, _DROP_A_CHUNK)
        host.evaluate("window.__dropRomChunk = 2")
        guest.click("#rom-accept-btn")

        # One 64 KB chunk short of the header: refused, and the bytes dropped.
        expect(guest.locator("#rom-progress-text")).to_have_text(
            "ROM transfer size mismatch — load manually", timeout=30000
        )
        assert guest.evaluate(_RECEIVED) is None

        # The host turns sharing off and on again; the guest, still without the
        # file, asks for it. It must come from the start: before the fix the
        # guest asked to resume from the short file's count with nothing held,
        # and that transfer could never be whole. (Before the fix the guest did
        # not even hear the host's new offer in the lobby: turning sharing off
        # had stopped it listening for the pre-game connection's signals.)
        sharing = host.locator("#opt-rom-sharing")
        sharing.uncheck()
        expect(sharing).not_to_be_checked()
        host.wait_for_timeout(500)
        sharing.check()

        expect(guest.locator("#rom-status")).to_contain_text("test.z64 (from host)", timeout=30000)
        assert guest.evaluate(_RECEIVED) == {"size": ROM_BYTES, "sum": _sum(ROM)}
    finally:
        for page in (host, guest):
            if page:
                page.close()
